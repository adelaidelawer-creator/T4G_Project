const cartItemsContainer = document.getElementById("cartItems");
const cartSubtotal = document.getElementById("cartSubtotal");
const cartTotal = document.getElementById("cartTotal");


/* =========================================
   DISPLAY CART
========================================= */

function displayCart() {

    if (!cartItemsContainer) {
        return;
    }


    let cart =
        JSON.parse(localStorage.getItem("alLuxeCart")) || [];


    /* EMPTY CART */

    if (cart.length === 0) {

        cartItemsContainer.innerHTML = `

            <div class="empty-cart">

                <i class="fa-solid fa-bag-shopping"></i>

                <h2>Your shopping bag is empty</h2>

                <p>
                    Discover something beautiful from our collections.
                </p>

                <a href="collections.html">
                    Explore Collections
                </a>

            </div>

        `;


        if (cartSubtotal) {
            cartSubtotal.textContent = "GH₵0.00";
        }


        if (cartTotal) {
            cartTotal.textContent = "GH₵0.00";
        }


        return;
    }


    /* CLEAR CART */

    cartItemsContainer.innerHTML = "";


    let subtotal = 0;


    /* DISPLAY PRODUCTS */

    cart.forEach(function(item, index) {

        const itemTotal =
            item.price * item.quantity;


        subtotal += itemTotal;


        const cartItem =
            document.createElement("div");


        cartItem.className = "cart-item";


        cartItem.innerHTML = `

            <!-- PRODUCT -->

            <div class="cart-product">

                <img
                    src="${item.image}"
                    alt="${item.name}"
                    class="cart-item-image"
                >

                <div class="cart-product-info">

                    <h3>
                        ${item.name}
                    </h3>

                    <button
                        type="button"
                        class="product-details-btn"
                        data-id="${item.id}">

                        Product Details

                    </button>

                </div>

            </div>


            <!-- PRICE -->

            <div class="cart-price">

                GH₵${item.price.toFixed(2)}

            </div>


            <!-- QUANTITY -->

            <div class="cart-quantity">

                <button
                    type="button"
                    class="cart-decrease"
                    data-index="${index}">

                    −

                </button>


                <span>
                    ${item.quantity}
                </span>


                <button
                    type="button"
                    class="cart-increase"
                    data-index="${index}">

                    +

                </button>

            </div>


            <!-- TOTAL -->

            <div class="cart-item-total">

                <strong>
                    GH₵${itemTotal.toFixed(2)}
                </strong>

                <button
                    type="button"
                    class="remove-item"
                    data-index="${index}">

                    Remove

                </button>

            </div>

        `;


        cartItemsContainer.appendChild(cartItem);

    });


    /* UPDATE TOTALS */

    if (cartSubtotal) {

        cartSubtotal.textContent =
            `GH₵${subtotal.toFixed(2)}`;

    }


    if (cartTotal) {

        cartTotal.textContent =
            `GH₵${subtotal.toFixed(2)}`;

    }


    addCartControls();

}



/* =========================================
   CART CONTROLS
========================================= */

function addCartControls() {


    /* INCREASE */

    document.querySelectorAll(".cart-increase")
        .forEach(function(button) {

            button.addEventListener("click", function() {

                const index =
                    Number(button.dataset.index);


                let cart =
                    JSON.parse(localStorage.getItem("alLuxeCart")) || [];


                cart[index].quantity++;


                localStorage.setItem(
                    "alLuxeCart",
                    JSON.stringify(cart)
                );


                displayCart();

            });

        });



    /* DECREASE */

    document.querySelectorAll(".cart-decrease")
        .forEach(function(button) {

            button.addEventListener("click", function() {

                const index =
                    Number(button.dataset.index);


                let cart =
                    JSON.parse(localStorage.getItem("alLuxeCart")) || [];


                if (cart[index].quantity > 1) {

                    cart[index].quantity--;

                } else {

                    cart.splice(index, 1);

                }


                localStorage.setItem(
                    "alLuxeCart",
                    JSON.stringify(cart)
                );


                displayCart();

            });

        });



    /* REMOVE */

    document.querySelectorAll(".remove-item")
        .forEach(function(button) {

            button.addEventListener("click", function() {

                const index =
                    Number(button.dataset.index);


                let cart =
                    JSON.parse(localStorage.getItem("alLuxeCart")) || [];


                cart.splice(index, 1);


                localStorage.setItem(
                    "alLuxeCart",
                    JSON.stringify(cart)
                );


                displayCart();

            });

        });



    /* PRODUCT DETAILS */

    document.querySelectorAll(".product-details-btn")
        .forEach(function(button) {

            button.addEventListener("click", function() {

                const productId =
                    button.dataset.id;


                window.location.href =
                    `product.details.html?product=${productId}`;

            });

        });

}



