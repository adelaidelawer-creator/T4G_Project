const wishlistItemsContainer =
    document.getElementById("wishlistItems");


function displayWishlist() {

    if (!wishlistItemsContainer) {
        return;
    }


    let wishlist =
        JSON.parse(
            localStorage.getItem("alLuxeWishlist")
        ) || [];


    /* =====================================
       EMPTY WISHLIST
    ===================================== */

    if (wishlist.length === 0) {

        wishlistItemsContainer.innerHTML = `

            <div class="empty-cart">

                <i class="fa-regular fa-heart"></i>

                <h2>
                    Your wishlist is empty
                </h2>

                <p>
                    Save your favorite pieces and they will appear here.
                </p>

                <a href="collections.html">
                    Explore Collections
                </a>

            </div>

        `;

        return;
    }


    /* =====================================
       DISPLAY WISHLIST PRODUCTS
    ===================================== */

    wishlistItemsContainer.innerHTML = "";


    wishlist.forEach(function (item) {

        const card =
            document.createElement("div");


        card.className =
            "card";


        card.innerHTML = `

            <img
                src="${item.image}"
                alt="${item.name}"
            >


            <h3>
                ${item.name}
            </h3>


            <p class="wishlist-price">
                GH₵${Number(item.price).toFixed(2)}
            </p>


            <div class="wishlist-actions">



                <button
                    type="button"
                    class="wishlist-cart-btn"
                    data-id="${item.id}">

                    Add to Cart

                </button>


                <button
                    type="button"
                    class="wishlist-remove-btn"
                    data-id="${item.id}">

                    <i class="fa-regular fa-trash-can"></i>
                    Remove

                </button>

            </div>

        `;


        wishlistItemsContainer.appendChild(card);

    });


    addWishlistControls();

}


/* =========================================
   WISHLIST CONTROLS
========================================= */

function addWishlistControls() {


    /* =====================================
       REMOVE FROM WISHLIST
    ===================================== */

    document
        .querySelectorAll(".wishlist-remove-btn")
        .forEach(function (button) {

            button.addEventListener(
                "click",
                function () {

                    const productId =
                        button.dataset.id;


                    let wishlist =
                        JSON.parse(
                            localStorage.getItem(
                                "alLuxeWishlist"
                            )
                        ) || [];


                    wishlist =
                        wishlist.filter(
                            function (item) {

                                return item.id !== productId;

                            }
                        );


                    localStorage.setItem(
                        "alLuxeWishlist",
                        JSON.stringify(wishlist)
                    );


                    displayWishlist();

                }
            );

        });



    /* =====================================
       ADD WISHLIST ITEM TO CART
    ===================================== */

    document
        .querySelectorAll(".wishlist-cart-btn")
        .forEach(function (button) {

            button.addEventListener(
                "click",
                function () {

                    const productId =
                        button.dataset.id;


                    let wishlist =
                        JSON.parse(
                            localStorage.getItem(
                                "alLuxeWishlist"
                            )
                        ) || [];


                    const wishlistProduct =
                        wishlist.find(
                            function (item) {

                                return item.id === productId;

                            }
                        );


                    if (!wishlistProduct) {
                        return;
                    }


                    let cart =
                        JSON.parse(
                            localStorage.getItem(
                                "alLuxeCart"
                            )
                        ) || [];


                    const existingProduct =
                        cart.find(
                            function (item) {

                                return item.id === productId;

                            }
                        );


                    if (existingProduct) {

                        existingProduct.quantity += 1;

                    } else {

                        cart.push({

                            id:
                                wishlistProduct.id,

                            name:
                                wishlistProduct.name,

                            price:
                                wishlistProduct.price,

                            image:
                                wishlistProduct.image,

                            quantity: 1

                        });

                    }


                    localStorage.setItem(
                        "alLuxeCart",
                        JSON.stringify(cart)
                    );


                    alert(
                        `${wishlistProduct.name} has been added to your cart.`
                    );


                    updateWishlistCartCount();

                }
            );

        });

}


/* =========================================
   UPDATE CART COUNT
========================================= */

function updateWishlistCartCount() {

    const cartCount =
        document.querySelector(".cart-count");


    if (!cartCount) {
        return;
    }


    let cart =
        JSON.parse(
            localStorage.getItem("alLuxeCart")
        ) || [];


    const totalQuantity =
        cart.reduce(
            function (total, item) {

                return total + Number(item.quantity || 0);

            },
            0
        );


    cartCount.textContent =
        totalQuantity;

}


