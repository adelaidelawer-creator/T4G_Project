/* =========================================
   AL LUXE PRODUCT SEARCH
========================================= */

document.addEventListener("DOMContentLoaded", function () {

    const searchInput = document.getElementById("productSearchInput");
    const searchForm = document.getElementById("productSearchForm");
    const searchResults = document.getElementById("searchResults");
    const searchEmpty = document.getElementById("searchEmpty");
    const resultCount = document.getElementById("searchResultCount");

    // Only run this code on the search page
    if (!searchInput || !searchResults) {
        return;
    }


    /* =========================================
       DISPLAY PRODUCTS
    ========================================= */

    function displayProducts(productList) {

        searchResults.innerHTML = "";

        if (productList.length === 0) {

            searchEmpty.style.display = "flex";
            resultCount.textContent = "";

            return;
        }

        searchEmpty.style.display = "none";

        resultCount.textContent =
            `${productList.length} ${productList.length === 1 ? "piece" : "pieces"} found`;


        productList.forEach(function (product) {

            const card = document.createElement("a");

            card.className = "search-result-card";

                card.href = `product.details.html?product=${encodeURIComponent(product.id)}`;


            card.innerHTML = `

                <div class="search-result-image">

                    <img
                        src="${product.image}"
                        alt="${product.name}"
                    >

                </div>


                <div class="search-result-info">

                    <span class="search-result-type">
                        AL LUXE COLLECTION
                    </span>

                    <h3>
                        ${product.name}
                    </h3>

                    <p>
                        ${product.description}
                    </p>

                    <strong>
                        GH₵${product.price.toFixed(2)}
                    </strong>

                    <span class="view-product">
                        View Product
                        <i class="fa-solid fa-arrow-right"></i>
                    </span>

                </div>

            `;

            searchResults.appendChild(card);

        });

    }


    /* =========================================
       GET ALL PRODUCTS
    ========================================= */

    const allProducts = Object.entries(products).map(
        function ([id, product]) {

            return {
                id: id,
                ...product
            };

        }
    );


    /* =========================================
       SEARCH PRODUCTS
    ========================================= */

    function searchProducts(searchTerm) {

        const term = searchTerm.toLowerCase().trim();

        if (term === "") {

            displayProducts(allProducts);

            return;
        }


        const filteredProducts = allProducts.filter(
            function (product) {

                return (
                    product.name.toLowerCase().includes(term) ||
                    product.description.toLowerCase().includes(term)
                );

            }
        );


        displayProducts(filteredProducts);

    }


    /* =========================================
       LIVE SEARCH
    ========================================= */

    searchInput.addEventListener("input", function () {

        searchProducts(searchInput.value);

    });


    /* =========================================
       FORM SUBMISSION
    ========================================= */

    if (searchForm) {

        searchForm.addEventListener("submit", function (event) {

            event.preventDefault();

            searchProducts(searchInput.value);

        });

    }


    /* =========================================
       SHOW ALL PRODUCTS INITIALLY
    ========================================= */

    displayProducts(allProducts);

});


